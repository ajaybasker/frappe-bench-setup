# ===================================================================== environment
@dataclass
class ToolEnv:
    """Runtimes chosen for a bench; prepended to PATH for every bench command."""

    path_entries: list[Path] = field(default_factory=list)
    python: str | None = None
    node_bin: str | None = None

    def add(self, entry: Path | str | None) -> None:
        if entry:
            p = Path(entry)
            if p not in self.path_entries:
                self.path_entries.append(p)

    def env(self) -> dict[str, str]:
        env = dict(os.environ)
        parts = [str(p) for p in self.path_entries] + env.get("PATH", "").split(os.pathsep)
        env["PATH"] = os.pathsep.join(dict.fromkeys(p for p in parts if p))
        return env

    def which(self, program: str) -> str | None:
        return shutil.which(program, path=self.env()["PATH"])

    def script(self) -> str:
        entries = ":".join(str(p) for p in self.path_entries)
        return (
            "# Generated by frappe-setup. Puts the runtimes chosen for this bench on PATH.\n"
            "# Usage: source this file, then run bench commands.\n"
            f'export PATH="{entries}:$PATH"\n'
        )

    def to_dict(self) -> dict[str, object]:
        return {"path_entries": [str(p) for p in self.path_entries], "python": self.python, "node_bin": self.node_bin}

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> ToolEnv:
        return cls(
            path_entries=[Path(str(p)) for p in (data.get("path_entries") or [])],
            python=data.get("python"),
            node_bin=data.get("node_bin"),
        )


def managed_dirs() -> dict[str, Path]:
    base = data_dir()
    return {
        "node": base / "node",
        "npm_global": base / "npm-global",
        "tools": base / "tools",
        "tools_bin": base / "tools" / "bin",
        "env": base / "env",
    }


def default_extra_path() -> list[Path]:
    """Locations of tools this program may have installed earlier."""
    dirs = managed_dirs()
    return [dirs["npm_global"] / "bin", dirs["tools_bin"], user_bin_dir()]


# ===================================================================== privileges
class Privilege:
    """Gatekeeper for sudo. Nothing privileged runs before `authorize()` succeeded."""

    def __init__(self, runner: Runner, ui: UI, facts: SystemFacts) -> None:
        self.runner = runner
        self.ui = ui
        self.facts = facts
        self.authorized = False

    @property
    def is_root(self) -> bool:
        return self.facts.is_root

    def wrap(self, argv: list[str], env: dict[str, str] | None = None) -> list[str]:
        if not self.authorized:
            raise SetupError("Internal error: privileged command without authorization", phase=PHASE)
        env_args = ["env", *[f"{k}={v}" for k, v in (env or {}).items()]] if env else []
        if self.is_root:
            return [*env_args, *argv]
        return ["sudo", "-n", *env_args, *argv]

    def authorize(self, commands: list[str], reason: str) -> None:
        if self.authorized:
            self.refresh()
            return
        who = "as root" if self.is_root else "with sudo"
        self.ui.panel("\n".join(f"$ {c}" for c in commands), title=f"Commands that will run {who}", style="yellow")
        self.ui.info(reason)
        if not self.ui.confirm(f"Run these commands {who}?", default=False):
            raise UserAbort(
                "Privileged changes were declined. Run the commands above yourself, then rerun "
                "frappe-setup; it will detect the installed packages."
            )
        if not self.is_root:
            if not self.facts.sudo_available:
                raise SetupError(
                    "sudo is not available.",
                    phase=PHASE,
                    remedy="Ask an administrator to run the commands above, then rerun frappe-setup.",
                    retry_safe=True,
                )
            self._validate_sudo()
        self.authorized = True

    def _validate_sudo(self) -> None:
        if self.runner.run(["sudo", "-n", "-v"], timeout=15, quiet=True, phase=PHASE).ok:
            return
        if not self.ui.interactive:
            raise SetupError(
                "sudo needs a password but the installer is running non-interactively.",
                phase=PHASE,
                cause="No cached sudo credentials and no terminal to ask for a password.",
                remedy="Run `sudo -v` in the same terminal right before frappe-setup, or run interactively.",
                retry_safe=True,
            )
        self.ui.info("sudo may ask for your password.")
        if self.runner.run_on_terminal(["sudo", "-v"], phase=PHASE) != 0:
            raise SetupError("sudo authentication failed.", phase=PHASE, retry_safe=True)

    def refresh(self) -> None:
        if not self.is_root:
            if not self.runner.run(["sudo", "-n", "-v"], timeout=15, quiet=True, phase=PHASE).ok:
                self._validate_sudo()


# ===================================================================== actions
@dataclass
class Action:
    key: str
    title: str
    privileged: bool
    preview: list[str]
    run: Callable[[], object]


@dataclass
class DepContext:
    runner: Runner
    ui: UI
    facts: SystemFacts
    matrix: Matrix
    branch: BranchSpec
    report: PreflightReport
    privilege: Privilege
    db_engine: str = "mariadb"
    want_wkhtmltopdf: bool = False
    want_cron: bool = False
    toolenv: ToolEnv = field(default_factory=ToolEnv)


def _apt(ctx: DepContext, args: list[str], title: str) -> None:
    ctx.privilege.refresh()
    argv = ctx.privilege.wrap(
        ["apt-get", "-o", "DPkg::Lock::Timeout=300", "-o", "Acquire::Retries=5", *args],
        env={"DEBIAN_FRONTEND": "noninteractive"},
    )
    with ctx.ui.progress(title) as on_line:
        result = ctx.runner.run(argv, timeout=APT_TIMEOUT, on_line=on_line, phase=PHASE, new_session=False, retries=2)
    if not result.ok:
        raise command_error(result, phase=PHASE, message=f"{title} failed")


def apt_candidate(runner: Runner, package: str) -> Version | None:
    """Version apt would install (from `apt-cache policy`), or None."""
    if not shutil.which("apt-cache"):
        return None
    result = runner.run(["apt-cache", "policy", package], timeout=60, quiet=True, phase=PHASE)
    m = re.search(r"Candidate:\s*(\S+)", result.output)
    if not m or m.group(1) == "(none)":
        return None
    return parse_version(m.group(1).split(":", 1)[-1])


def _venv_python(facts: SystemFacts) -> str | None:
    """An interpreter with a working venv module, for creating the tools venv."""
    for p in facts.pythons:
        if not p.source.endswith("-no-venv") and p.source in ("system", "path", "pyenv", "uv"):
            if satisfies(p.version, ">=3.8"):
                return p.path
    return None


def plan(ctx: DepContext) -> list[Action]:
    facts, matrix, branch, report = ctx.facts, ctx.matrix, ctx.branch, ctx.report
    apt = matrix.apt_packages
    installed = facts.apt_installed
    is_debian = facts.os_id in ("ubuntu", "debian") or "debian" in facts.os_like
    actions: list[Action] = []
    need: list[str] = []

    def want(*pkgs: str) -> None:
        for p in pkgs:
            if p not in installed and p not in need:
                need.append(p)

    if is_debian:
        want(*apt.get("base", []))
        want(*apt.get("build", []))
        want(*apt.get("redis", []) if not facts.tool("redis-server").found else [])
        py = report.python
        if py is not None and py.source.startswith("system"):
            mm = ".".join(py.version.split(".")[:2])
            want(f"python{mm}-dev", f"python{mm}-venv")
        if ctx.db_engine == "mariadb":
            want(*apt.get("mariadb_client_libs", []))
        else:
            want(*apt.get("postgres_client", []))
        if ctx.want_wkhtmltopdf and not facts.tool("wkhtmltopdf").found:
            want(*apt.get("pdf_wkhtmltopdf", []))
        if ctx.want_cron and not facts.tool("crontab").found:
            want(*apt.get("cron", []))

    mariadb_item = report.item("MariaDB server")
    mariadb_repo_series: str | None = None
    if ctx.db_engine == "mariadb" and mariadb_item and mariadb_item.status == MISSING:
        series = str(branch.install.get("mariadb_series", "distribution"))
        candidate = apt_candidate(ctx.runner, "mariadb-server")
        if series == "distribution" or (candidate and satisfies(candidate, report.requirements.mariadb)):
            want(*apt.get("mariadb_server", []))
        else:
            mariadb_repo_series = series

    if need:
        if not is_debian:
            raise SetupError("Automatic package installation is only implemented for Ubuntu/Debian.", phase=PHASE)
        pkgs = list(need)
        actions.append(
            Action(
                "apt",
                f"Install system packages: {' '.join(pkgs)}",
                True,
                [
                    "apt-get update",
                    f"apt-get install -y --no-install-recommends {' '.join(pkgs)}",
                ],
                lambda: _install_apt(ctx, pkgs),
            )
        )

    if mariadb_repo_series:
        repo = matrix.mariadb_repository
        sources = _mariadb_sources_text(repo, mariadb_repo_series, facts)
        actions.append(
            Action(
                "mariadb-repo",
                f"Add the official MariaDB {mariadb_repo_series} APT repository and install MariaDB",
                True,
                [
                    f"install -m 0644 <downloaded key, fingerprint {repo.get('key_fingerprint')}> "
                    f"{repo.get('keyring_path')}",
                    f"install -m 0644 <sources file> {repo.get('sources_path')}   # {sources.splitlines()[1]}",
                    "apt-get update",
                    "apt-get install -y mariadb-server mariadb-client",
                ],
                lambda: _install_mariadb_repo(ctx, mariadb_repo_series),
            )
        )

    if ctx.db_engine == "mariadb" and (
        (mariadb_item and mariadb_item.status == MISSING)
        or (report.item("MariaDB service") and report.item("MariaDB service").status == MISSING)  # type: ignore[union-attr]
    ):
        actions.append(
            Action(
                "mariadb-service",
                "Make sure the MariaDB service is running",
                True,
                ["systemctl start mariadb   (or `service mariadb start` without systemd), only if not running"],
                lambda: ensure_mariadb_running(ctx),
            )
        )

    # ---------------------------------------------------------------- user space
    py_item = report.item("Python")
    bench_item = report.item("Bench CLI")
    need_python = py_item is not None and py_item.status == MISSING and report.python is None
    need_bench = bench_item is not None and bench_item.status in (MISSING, FAIL)
    if (need_python or need_bench) and not facts.tool("uv").found:
        actions.append(
            Action(
                "uv",
                "Install uv (Python package and interpreter manager) in user space",
                False,
                [f"python3 -m venv {managed_dirs()['tools']}/uv-venv && pip install uv"],
                lambda: install_uv(ctx),
            )
        )
    if need_python:
        version = str(branch.install["python"])
        actions.append(
            Action(
                "python",
                f"Install Python {version} with uv (user space; system Python untouched)",
                False,
                [f"uv python install {version}"],
                lambda: install_python(ctx, version),
            )
        )
    node_item = report.item("Node.js")
    if node_item is not None and node_item.status == MISSING:
        major = int(branch.install["node_major"])
        actions.append(
            Action(
                "node",
                f"Install Node.js {major} from nodejs.org into {managed_dirs()['node']} (checksum verified)",
                False,
                [
                    f"download {NODE_DIST}/latest-v{major}.x/node-v{major}.*-linux-{_node_arch()}.tar.gz "
                    "+ SHASUMS256.txt"
                ],
                lambda: install_node(ctx, major),
            )
        )
    yarn_item = report.item("Yarn")
    if yarn_item is not None and yarn_item.status in (MISSING, FAIL):
        actions.append(
            Action(
                "yarn",
                f"Install Yarn 1.x into {managed_dirs()['npm_global']}",
                False,
                [f"npm install --global --prefix {managed_dirs()['npm_global']} yarn@1"],
                lambda: install_yarn(ctx),
            )
        )
    if need_bench:
        upgrade = bench_item is not None and bench_item.status == FAIL
        actions.append(
            Action(
                "bench",
                "Upgrade the Bench CLI" if upgrade else "Install the Bench CLI",
                False,
                [f"uv tool install {'--upgrade ' if upgrade else ''}frappe-bench"],
                lambda: install_bench(ctx, upgrade=upgrade),
            )
        )
    return actions


def execute(ctx: DepContext, actions: list[Action]) -> None:
    """Ask for authorization, then run the actions in order."""
    if not actions:
        return
    user_actions = [a for a in actions if not a.privileged]
    priv_actions = [a for a in actions if a.privileged]
    ctx.ui.info("[bold]Planned changes:[/]")
    for a in actions:
        tag = "[yellow]sudo[/]" if a.privileged else "[green]user[/]"
        ctx.ui.info(f"  • [{tag}] {a.title}")
    if user_actions and not ctx.ui.confirm("Install the user-space tools listed above?", default=True):
        raise UserAbort("User-space tool installation was declined.")
    if priv_actions:
        ctx.privilege.authorize(
            [c for a in priv_actions for c in a.preview],
            "These install or start system packages. Nothing else on the system is changed.",
        )
    for action in actions:
        get_logger(PHASE).info("action %s: %s", action.key, action.title)
        action.run()


# ===================================================================== installers
def _install_apt(ctx: DepContext, packages: list[str]) -> None:
    _apt(ctx, ["update"], "Updating package lists")
    _apt(ctx, ["install", "-y", "--no-install-recommends", *packages], f"Installing {len(packages)} system package(s)")
    from .system import dpkg_installed

    present = dpkg_installed(ctx.runner, packages)
    missing = [p for p in packages if p not in present]
    if missing:
        raise SetupError(
            f"Packages are still not installed after apt-get: {' '.join(missing)}",
            phase=PHASE,
            remedy=f"Run `sudo apt-get install {' '.join(missing)}` to see the error.",
            retry_safe=True,
        )
    ctx.facts.apt_installed.update(present)


def _mariadb_sources_text(repo: dict[str, str], series: str, facts: SystemFacts) -> str:
    arch = {"x86_64": "amd64", "aarch64": "arm64"}.get(facts.arch, facts.arch)
    return (
        "# MariaDB repository added by frappe-setup\n"
        "X-Repolib-Name: MariaDB\n"
        "Types: deb\n"
        f"URIs: {repo['url']}/{series}/{facts.os_id}\n"
        f"Suites: {facts.os_codename}\n"
        "Components: main\n"
        f"Architectures: {arch}\n"
        f"Signed-By: {repo['keyring_path']}\n"
    )


def _gpg_fingerprints(runner: Runner, key_file: Path) -> list[str]:
    gpg = shutil.which("gpg")
    if not gpg:
        raise SetupError("gpg is required to verify the MariaDB signing key.", phase=PHASE, remedy="apt: gnupg")
    with tempfile.TemporaryDirectory(prefix="frappe-setup-gpg-") as home:
        os.chmod(home, 0o700)
        result = runner.run(
            [gpg, "--homedir", home, "--batch", "--with-colons", "--show-keys", str(key_file)],
            timeout=60,
            quiet=True,
            phase=PHASE,
        )
    return [line.split(":")[9] for line in result.output.splitlines() if line.startswith("fpr:")]


def _install_mariadb_repo(ctx: DepContext, series: str) -> None:
    repo = ctx.matrix.mariadb_repository
    keyring, sources_path = Path(repo["keyring_path"]), Path(repo["sources_path"])
    existing = sorted(Path("/etc/apt/sources.list.d").glob("mariadb*"))
    if existing and sources_path not in existing:
        raise SetupError(
            f"A MariaDB repository is already configured ({', '.join(map(str, existing))}).",
            phase=PHASE,
            remedy="frappe-setup does not modify existing repository configuration. Install MariaDB "
            f"{series} from it manually (`sudo apt-get install mariadb-server`) and rerun.",
            retry_safe=False,
        )
    # gnupg may have just been installed by the apt action.
    work = Path(tempfile.mkdtemp(prefix="frappe-setup-mariadb-"))
    try:
        key = work / "mariadb-keyring.pgp"
        key.write_bytes(fetch_bytes(repo["key_url"], phase=PHASE))
        fingerprints = _gpg_fingerprints(ctx.runner, key)
        expected = repo["key_fingerprint"].replace(" ", "").upper()
        if expected not in [f.upper() for f in fingerprints]:
            raise SetupError(
                "The downloaded MariaDB signing key does not have the expected fingerprint.",
                phase=PHASE,
                cause=f"Expected {expected}, got {', '.join(fingerprints) or 'no key'}.",
                remedy="Do not continue; check your network for interception and report the issue.",
                retry_safe=False,
            )
        sources = work / "mariadb.sources"
        sources.write_text(_mariadb_sources_text(repo, series, ctx.facts), encoding="utf-8")
        ctx.privilege.refresh()
        for src, dest in ((key, keyring), (sources, sources_path)):
            result = ctx.runner.run(
                ctx.privilege.wrap(["install", "-m", "0644", "-o", "root", "-g", "root", str(src), str(dest)]),
                timeout=60,
                phase=PHASE,
                new_session=False,
            )
            if not result.ok:
                raise command_error(result, phase=PHASE, message=f"Could not install {dest}")
    finally:
        shutil.rmtree(work, ignore_errors=True)
    _install_apt(ctx, list(ctx.matrix.apt_packages.get("mariadb_server", [])))


def mariadb_alive(runner: Runner) -> bool:
    exe = shutil.which("mariadb-admin") or shutil.which("mysqladmin")
    if not exe:
        return False
    # `mariadb-admin ping` exits 0 when the server answers, even if access is denied.
    result = runner.run([exe, "--connect-timeout=5", "ping"], timeout=20, quiet=True, phase=PHASE)
    return result.ok or "Access denied" in result.output


def ensure_mariadb_running(ctx: DepContext) -> None:
    if mariadb_alive(ctx.runner):
        return
    ctx.privilege.refresh()
    argv = ["systemctl", "start", "mariadb"] if ctx.facts.systemd else ["service", "mariadb", "start"]
    result = ctx.runner.run(ctx.privilege.wrap(argv), timeout=180, phase=PHASE, new_session=False)
    import time

    for _ in range(30):
        if mariadb_alive(ctx.runner):
            return
        time.sleep(1)
    raise command_error(
        result,
        phase=PHASE,
        message="MariaDB did not start",
        remedy="Check `sudo journalctl -u mariadb` or /var/log/mysql/error.log.",
        retry_safe=True,
    )


def _uv(ctx: DepContext) -> str:
    exe = shutil.which("uv", path=ctx.toolenv.env()["PATH"]) or ctx.facts.tool("uv").path
    if not exe:
        raise SetupError("uv is not available.", phase=PHASE, retry_safe=True)
    return exe


def install_uv(ctx: DepContext) -> None:
    dirs = managed_dirs()
    python = _venv_python(ctx.facts)
    if python is None:
        # python3-venv may have been installed in this run.
        python = shutil.which("python3")
    if python is None:
        raise SetupError("No Python interpreter with venv support found to install uv.", phase=PHASE)
    venv = dirs["tools"] / "uv-venv"
    ensure_private_dir(dirs["tools"])
    with ctx.ui.progress("Installing uv") as on_line:
        for argv in (
            [python, "-m", "venv", "--clear", str(venv)],
            [
                str(venv / "bin" / "python"),
                "-m",
                "pip",
                "install",
                "--disable-pip-version-check",
                "--upgrade",
                "uv>=0.5,<1",
            ],
        ):
            result = ctx.runner.run(argv, timeout=600, on_line=on_line, phase=PHASE, retries=2)
            if not result.ok:
                raise command_error(result, phase=PHASE, message="Installing uv failed")
    dirs["tools_bin"].mkdir(parents=True, exist_ok=True)
    link = dirs["tools_bin"] / "uv"
    if link.is_symlink() or link.exists():
        link.unlink()
    link.symlink_to(venv / "bin" / "uv")
    ctx.toolenv.add(dirs["tools_bin"])
    check = ctx.runner.run([str(link), "--version"], timeout=30, phase=PHASE)
    if not check.ok:
        raise command_error(check, phase=PHASE, message="uv was installed but does not run")


def install_python(ctx: DepContext, version: str) -> str:
    uv = _uv(ctx)
    with ctx.ui.progress(f"Installing Python {version}") as on_line:
        result = ctx.runner.run(
            [uv, "python", "install", version], timeout=1200, on_line=on_line, phase=PHASE, retries=2
        )
    if not result.ok:
        raise command_error(result, phase=PHASE, message=f"Installing Python {version} failed")
    found = ctx.runner.run([uv, "python", "find", version], timeout=60, phase=PHASE)
    path = found.output.strip().splitlines()[-1] if found.ok and found.output.strip() else ""
    verify = (
        ctx.runner.run(
            [path, "-c", "import sys,venv; print('%d.%d.%d' % sys.version_info[:3])"], timeout=60, phase=PHASE
        )
        if path
        else None
    )
    if not verify or not verify.ok or not satisfies(verify.output.strip(), ctx.report.requirements.python):
        raise SetupError(
            f"Python {version} was installed but could not be verified.",
            phase=PHASE,
            remedy=f"Run `uv python find {version}` to inspect.",
            retry_safe=True,
        )
    ctx.toolenv.python = path
    return path


def _node_arch() -> str:
    machine = platform.machine()
    return {"x86_64": "x64", "aarch64": "arm64"}.get(machine, machine)


def select_node_release(index: list[dict[str, object]], major: int, arch: str) -> str:
    """Newest release of `major` that ships a linux-<arch> build."""
    wanted = f"linux-{arch}"
    best: Version | None = None
    for entry in index:
        version = str(entry.get("version", ""))
        files = entry.get("files") or []
        parsed = parse_version(version)
        if parsed is None or parsed.major != major or wanted not in files:  # type: ignore[operator]
            continue
        if best is None or parsed > best:
            best = parsed
    if best is None:
        raise SetupError(f"No Node.js {major}.x release for linux-{arch} found on nodejs.org.", phase=PHASE)
    return f"v{best}"


def install_node(ctx: DepContext, major: int) -> Path:
    arch = _node_arch()
    index = fetch_json(f"{NODE_DIST}/index.json", phase=PHASE)
    version = select_node_release(index, major, arch)
    name = f"node-{version}-linux-{arch}"
    dirs = managed_dirs()
    target = dirs["node"] / name
    node_exe = target / "bin" / "node"
    if not node_exe.exists():
        archive_name = f"{name}.tar.gz"
        sums = fetch_bytes(f"{NODE_DIST}/{version}/SHASUMS256.txt", phase=PHASE).decode()
        expected = next((ln.split()[0] for ln in sums.splitlines() if ln.endswith(f"  {archive_name}")), None)
        if not expected:
            raise SetupError(f"{archive_name} is not listed in SHASUMS256.txt.", phase=PHASE)
        work = Path(tempfile.mkdtemp(prefix="frappe-setup-node-", dir=ensure_private_dir(dirs["node"])))
        try:
            with ctx.ui.progress(f"Downloading Node.js {version}"):
                archive = download(f"{NODE_DIST}/{version}/{archive_name}", work / archive_name, phase=PHASE)
            actual = sha256_file(archive)
            if actual != expected:
                raise SetupError(
                    "Node.js download failed checksum verification.",
                    phase=PHASE,
                    cause=f"expected sha256 {expected}, got {actual}",
                    remedy="Retry; if it persists, check for a proxy altering downloads.",
                    retry_safe=True,
                )
            extract_dir = work / "x"
            safe_extract_tar(archive, extract_dir)
            os.replace(extract_dir / name, target)
        finally:
            shutil.rmtree(work, ignore_errors=True)
    result = ctx.runner.run([str(node_exe), "--version"], timeout=30, phase=PHASE)
    if not result.ok or not satisfies(result.output.strip(), ctx.report.requirements.node):
        raise command_error(result, phase=PHASE, message="Installed Node.js does not run or has the wrong version")
    ctx.toolenv.node_bin = str(target / "bin")
    ctx.toolenv.path_entries.insert(0, target / "bin")
    return target


def install_yarn(ctx: DepContext) -> None:
    prefix = managed_dirs()["npm_global"]
    npm = shutil.which("npm", path=ctx.toolenv.env()["PATH"])
    if not npm:
        raise SetupError("npm is not available to install Yarn.", phase=PHASE, retry_safe=True)
    with ctx.ui.progress("Installing Yarn") as on_line:
        result = ctx.runner.run(
            [npm, "install", "--global", "--prefix", str(prefix), "yarn@1"],
            env=ctx.toolenv.env(),
            timeout=600,
            on_line=on_line,
            phase=PHASE,
            retries=2,
        )
    if not result.ok:
        raise command_error(result, phase=PHASE, message="Installing Yarn failed")
    ctx.toolenv.add(prefix / "bin")
    check = ctx.runner.run([str(prefix / "bin" / "yarn"), "--version"], env=ctx.toolenv.env(), timeout=60, phase=PHASE)
    if not check.ok or not satisfies(check.output.strip(), ctx.report.requirements.yarn):
        raise command_error(check, phase=PHASE, message="Yarn was installed but does not run")


def install_bench(ctx: DepContext, *, upgrade: bool) -> None:
    uv = _uv(ctx)
    argv = [uv, "tool", "install", *(["--upgrade"] if upgrade else []), "frappe-bench"]
    with ctx.ui.progress("Installing the Bench CLI") as on_line:
        result = ctx.runner.run(argv, env=ctx.toolenv.env(), timeout=900, on_line=on_line, phase=PHASE, retries=2)
    if not result.ok:
        raise command_error(result, phase=PHASE, message="Installing the Bench CLI failed")
    ctx.toolenv.add(user_bin_dir())
    bench = user_bin_dir() / "bench"
    check = ctx.runner.run([str(bench), "--version"], env=ctx.toolenv.env(), timeout=60, phase=PHASE)
    if not check.ok or not satisfies(
        check.output.strip().splitlines()[-1] if check.output.strip() else "", ctx.report.requirements.bench
    ):
        raise command_error(check, phase=PHASE, message="Bench CLI was installed but does not run")


# ===================================================================== tool env
def build_toolenv(report: PreflightReport, existing: ToolEnv | None = None) -> ToolEnv:
    """PATH entries for the runtimes chosen by preflight (plus tool-managed locations)."""
    env = existing or ToolEnv()
    if report.node is not None:
        env.node_bin = env.node_bin or report.node.bin_dir
    if env.node_bin:
        env.add(env.node_bin)
    for p in default_extra_path():
        if p.is_dir():
            env.add(p)
    if report.python is not None and not env.python:
        env.python = report.python.path
    return env


def write_env_script(bench_name: str, bench_path: Path, toolenv: ToolEnv) -> Path:
    import hashlib

    from .utils import atomic_write_text

    digest = hashlib.sha1(str(bench_path).encode(), usedforsecurity=False).hexdigest()[:8]
    path = managed_dirs()["env"] / f"{bench_name}-{digest}.sh"
    atomic_write_text(path, toolenv.script() + f"# bench: {bench_path}\n", mode=0o644)
    return path


def blocking_after_install(report: PreflightReport) -> list[str]:
    return [f"{i.name}: {i.message or i.found}" for i in report.items if i.status in (FAIL, MISSING)]
