"""Dependency engine: plan, authorize, install and verify prerequisites.

Policy:
  * Existing compatible installations are always reused.
  * System packages (apt) are the only privileged changes, and they are shown and
    authorized before sudo is used.
  * Python, Node.js, Yarn, uv and Bench are installed in user space; system Python and
    system Node.js are never replaced.
"""

